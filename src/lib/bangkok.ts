export type BkkArea = { khet: string; khwaeng: string; zip: string };

const ALL: BkkArea[] = BANGKOK.flatMap(([khet, list]) =>
  list.map(([khwaeng, zip]) => ({ khet, khwaeng, zip })),
);

/** แขวงทั้งหมดที่ใช้รหัสไปรษณีย์นี้ (ว่าง = ไม่ใช่กรุงเทพ / ไม่อยู่ในพื้นที่ส่ง) */
export const areasByZip = (zip: string) => ALL.filter((a) => a.zip === zip);

export const isBangkokArea = (khet: string, khwaeng: string, zip: string) =>
  ALL.some((a) => a.khet === khet && a.khwaeng === khwaeng && a.zip === zip);
